package main

import "sync" // Подключаем инструменты для безопасной работы с несколькими потоками.

// Создаём хранилище, в котором каждому ключу соответствует своё значение.
type DataStore[K comparable, V any] struct {
	mu     sync.RWMutex // Защищаем данные от одновременного изменения.
	values map[K]V      // Здесь находятся все сохранённые элементы.
}

// Добавляем новое значение или заменяем старое по указанному ключу.
func (s *DataStore[K, V]) Put(key K, value V) {
	s.mu.Lock() // Закрываем доступ к изменению данных для других горутин.
	defer s.mu.Unlock() // После завершения функции снимаем блокировку.

	s.values[key] = value // Записываем значение в карту по его ключу.
}

// Ищем элемент в хранилище и возвращаем результат поиска.
func (s *DataStore[K, V]) Get(key K) (V, bool) {
	s.mu.RLock() // Разрешаем безопасное чтение данных.
	defer s.mu.RUnlock() // Освобождаем блокировку после чтения.

	result, found := s.values[key] // Проверяем, существует ли нужный ключ.
	return result, found // Возвращаем найденное значение и результат поиска.
}

// Удаляем запись, если переданный ключ существует.
func (s *DataStore[K, V]) Delete(key K) bool {
	s.mu.Lock() // Получаем доступ для изменения карты.
	defer s.mu.Unlock() // Гарантируем снятие блокировки.

	if _, found := s.values[key]; !found { // Проверяем наличие записи.
		return false // Если записи нет, сообщаем о неудачном удалении.
	}

	delete(s.values, key) // Убираем найденный элемент из карты.
	return true // Подтверждаем успешное удаление.
}

// Изменяем сохранённое значение с помощью переданной функции.
func (s *DataStore[K, V]) Update(key K, change func(V) V) (V, bool) {
	s.mu.Lock() // Блокируем хранилище на время изменения.
	defer s.mu.Unlock() // Освобождаем хранилище после выполнения операции.

	oldValue, found := s.values[key] // Получаем текущее значение по ключу.
	if !found { // Проверяем, удалось ли найти запись.
		var empty V // Создаём пустое значение нужного типа.
		return empty, false // Возвращаем пустое значение и false.
	}

	newValue := change(oldValue) // Применяем функцию к старому значению.
	s.values[key] = newValue // Сохраняем полученный результат.
	return newValue, true // Возвращаем обновлённое значение.
}

// Создаём хранилище, которое дополнительно запоминает порядок элементов.
type OrderedStore[K comparable, V any] struct {
	mu     sync.RWMutex // Отвечает за безопасный доступ к структуре.
	keys   []K          // Содержит ключи в порядке их добавления.
	data   map[K]V      // Хранит значения, связанные с ключами.
}

// Получаем все значения в том порядке, в котором добавлялись ключи.
func (s *OrderedStore[K, V]) Ordered() []V {
	s.mu.RLock() // Включаем режим безопасного чтения.
	defer s.mu.RUnlock() // Снимаем блокировку после завершения функции.

	result := make([]V, len(s.keys)) // Создаём срез под будущие результаты.

	for i, key := range s.keys { // Проходим по ключам в порядке добавления.
		result[i] = s.data[key] // Переносим соответствующее значение в срез.
	}

	return result // Возвращаем готовый список значений.
}

